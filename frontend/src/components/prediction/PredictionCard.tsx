import jsPDF from "jspdf";
import ConfidenceBar from "./ConfidenceBar";
import TopPredictions from "./TopPredictions";

const algorithmInfo = {
  AES: {
    type: "Symmetric",
    cipher: "Block Cipher",
    key: "128/192/256-bit",
    use: "HTTPS, Disk Encryption",
  },
  DES: {
    type: "Symmetric",
    cipher: "Block Cipher",
    key: "56-bit",
    use: "Legacy Systems",
  },
  "Triple DES": {
    type: "Symmetric",
    cipher: "Block Cipher",
    key: "168-bit",
    use: "Banking Systems",
  },
  Blowfish: {
    type: "Symmetric",
    cipher: "Block Cipher",
    key: "128–448-bit",
    use: "File Encryption",
  },
  RC4: {
    type: "Symmetric",
    cipher: "Stream Cipher",
    key: "Variable",
    use: "Legacy Wi-Fi",
  },
  ChaCha20: {
    type: "Symmetric",
    cipher: "Stream Cipher",
    key: "256-bit",
    use: "TLS, VPN",
  },
  RSA: {
    type: "Asymmetric",
    cipher: "Public-Key",
    key: "2048-bit",
    use: "Digital Signatures",
  },
  ECC: {
    type: "Asymmetric",
    cipher: "Public-Key",
    key: "256-bit",
    use: "TLS, Cryptocurrency",
  },
} as const;

type Prediction = {
  name: string;
  score: number;
};

type PredictionCardProps = {
  algorithm: string;
  confidence: number;
  inferenceTime: number;
  topPredictions: Prediction[];
  explanation: string;
  predictionId: string;
  timestamp: string;
};

export default function PredictionCard({
  algorithm,
  confidence,
  inferenceTime,
  topPredictions,
  explanation,
  predictionId,
  timestamp,
}: PredictionCardProps) {
  const info =
    algorithmInfo[
      algorithm as keyof typeof algorithmInfo
    ];

  const copyResult = () => {
    navigator.clipboard.writeText(
`Algorithm: ${algorithm}
Confidence: ${confidence.toFixed(2)}%
Inference Time: ${inferenceTime.toFixed(4)} s

${explanation}`
    );

    alert("Copied to clipboard!");
  };

  const downloadReport = () => {
    const pdf = new jsPDF();

    pdf.setFontSize(22);
    pdf.text(
      "CipherAnalytics Prediction Report",
      20,
      20
    );

    pdf.setFontSize(12);

    pdf.text(
      `Algorithm: ${algorithm}`,
      20,
      45
    );

    pdf.text(
      `Confidence: ${confidence.toFixed(2)}%`,
      20,
      55
    );

    pdf.text(
      `Inference Time: ${inferenceTime.toFixed(4)} s`,
      20,
      65
    );

    if (info) {
      pdf.text(`Type: ${info.type}`, 20, 80);
      pdf.text(`Cipher: ${info.cipher}`, 20, 90);
      pdf.text(`Key Size: ${info.key}`, 20, 100);
      pdf.text(`Common Use: ${info.use}`, 20, 110);
    }

    pdf.text(
      "Explanation",
      20,
      125
    );

    const explanationLines = pdf.splitTextToSize(
      explanation,
      170
    );

    pdf.text(
      explanationLines,
      20,
      135
    );

    const topY =
      135 +
      explanationLines.length * 7 +
      15;

    pdf.text(
      "Top Predictions",
      20,
      topY
    );

    topPredictions.forEach((item, index) => {
      pdf.text(
        `${index + 1}. ${item.name} - ${item.score.toFixed(2)}%`,
        25,
        topY + 15 + index * 10
      );
    });

    pdf.setFontSize(10);
    pdf.text(
      "Generated by CipherAnalytics",
      20,
      280
    );

    pdf.save("CipherAnalytics_Report.pdf");
  };

  return (
    <div className="rounded-2xl border border-slate-700 bg-slate-900 p-8 shadow-xl">

      <h2 className="text-2xl font-bold text-blue-400">
        Prediction Result
      </h2>

      <div className="mt-8 space-y-6">

        <div className="flex justify-between">
          <span className="text-slate-400">
            Algorithm
          </span>

          <span className="text-2xl font-bold text-white">
            {algorithm}
          </span>
        </div>

        <div className="flex justify-between">
          <span className="text-slate-400">
            Inference Time
          </span>

          <span className="font-semibold text-white">
            {inferenceTime.toFixed(4)} s
          </span>
        </div>

        {info && (
          <div className="rounded-xl border border-slate-700 bg-slate-800/60 p-4">
            <div className="grid grid-cols-2 gap-4 text-sm">

              <div>
                <p className="text-slate-400">
                  Type
                </p>
                <p className="font-semibold text-white">
                  {info.type}
                </p>
              </div>

              <div>
                <p className="text-slate-400">
                  Cipher
                </p>
                <p className="font-semibold text-white">
                  {info.cipher}
                </p>
              </div>

              <div>
                <p className="text-slate-400">
                  Key Size
                </p>
                <p className="font-semibold text-white">
                  {info.key}
                </p>
              </div>

              <div>
                <p className="text-slate-400">
                  Common Use
                </p>
                <p className="font-semibold text-white">
                  {info.use}
                </p>
              </div>

            </div>
          </div>
        )}

      </div>

      <div className="mt-8">
        <ConfidenceBar confidence={confidence} />
      </div>

      {explanation && (
        <div className="mt-8 rounded-xl border border-slate-700 bg-slate-800/60 p-4">
          <h3 className="mb-2 text-sm font-semibold uppercase tracking-wide text-slate-400">
            Why this algorithm?
          </h3>

          <p className="text-sm leading-relaxed text-slate-200">
            {explanation}
          </p>
        </div>
      )}

      <button
        onClick={copyResult}
        className="mt-6 w-full rounded-xl bg-emerald-600 px-6 py-3 font-semibold text-white hover:bg-emerald-700"
      >
        Copy Result
      </button>

      <button
        onClick={downloadReport}
        className="mt-4 w-full rounded-xl bg-indigo-600 px-6 py-3 font-semibold text-white transition hover:bg-indigo-700"
      >
        Download PDF Report
      </button>

      <div className="mt-8">
        <TopPredictions predictions={topPredictions} />
      </div>

    </div>
  );
}