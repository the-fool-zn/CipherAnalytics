import jsPDF from "jspdf";
import ConfidenceBar from "./ConfidenceBar";
import TopPredictions from "./TopPredictions";

type Prediction = {
  name: string;
  score: number;
};

type PredictionCardProps = {
  algorithm: string;
  confidence: number;
  inferenceTime: number;
  topPredictions: Prediction[];
  explanation: string;
};

export default function PredictionCard({
  algorithm,
  confidence,
  inferenceTime,
  topPredictions,
  explanation,
}: PredictionCardProps) {

  const copyResult = () => {
    navigator.clipboard.writeText(
`Algorithm: ${algorithm}
Confidence: ${confidence.toFixed(2)}%
Inference Time: ${inferenceTime.toFixed(4)}s

${explanation}`
    );

    alert("Copied to clipboard!");
  };


  const downloadReport = () => {
    const pdf = new jsPDF();

    pdf.setFontSize(22);
    pdf.text(
      "CipherAnalytics Prediction Report",
      20,
      20
    );

    pdf.setFontSize(12);

    pdf.text(
      `Algorithm: ${algorithm}`,
      20,
      45
    );

    pdf.text(
      `Confidence: ${confidence.toFixed(2)}%`,
      20,
      55
    );

    pdf.text(
      `Inference Time: ${inferenceTime.toFixed(4)} s`,
      20,
      65
    );

    pdf.text(
      "Explanation",
      20,
      80
    );

    const explanationLines = pdf.splitTextToSize(explanation, 170);
    pdf.text(explanationLines, 20, 90);

    const topPredictionsY = 90 + explanationLines.length * 7 + 15;

    pdf.text(
      "Top Predictions",
      20,
      topPredictionsY
    );


    topPredictions.forEach((item, index) => {
      pdf.text(
        `${index + 1}. ${item.name} - ${item.score.toFixed(2)}%`,
        25,
        topPredictionsY + 15 + index * 10
      );
    });


    pdf.setFontSize(10);

    pdf.text(
      "Generated by CipherAnalytics",
      20,
      270
    );


    pdf.save(
      "CipherAnalytics_Report.pdf"
    );
  };


  return (
    <div className="rounded-2xl border border-slate-700 bg-slate-900 p-8 shadow-xl">

      <h2 className="text-2xl font-bold text-blue-400">
        Prediction Result
      </h2>


      <div className="mt-8 space-y-6">

        <div className="flex justify-between">
          <span className="text-slate-400">
            Algorithm
          </span>

          <span className="text-2xl font-bold text-white">
            {algorithm}
          </span>
        </div>


        <div className="flex justify-between">
          <span className="text-slate-400">
            Inference Time
          </span>

          <span className="font-semibold text-white">
            {inferenceTime.toFixed(4)} s
          </span>
        </div>

      </div>


      <div className="mt-8">
        <ConfidenceBar confidence={confidence} />
      </div>


      {explanation && (
        <div className="mt-8 rounded-xl border border-slate-700 bg-slate-800/60 p-4">
          <h3 className="mb-2 text-sm font-semibold uppercase tracking-wide text-slate-400">
            Why this algorithm?
          </h3>
          <p className="text-sm leading-relaxed text-slate-200">
            {explanation}
          </p>
        </div>
      )}


      <button
        onClick={copyResult}
        className="mt-6 w-full rounded-xl bg-emerald-600 px-6 py-3 font-semibold text-white hover:bg-emerald-700"
      >
        Copy Result
      </button>


      <button
        onClick={downloadReport}
        className="mt-4 w-full rounded-xl bg-indigo-600 px-6 py-3 font-semibold text-white hover:bg-indigo-700 transition"
      >
        Download PDF Report
      </button>


      <div className="mt-8">
        <TopPredictions predictions={topPredictions} />
      </div>


    </div>
  );
}